async def test_an_identical_replay_is_honoured_even_after_the_round_moved_on() -> None:
    """Where the two frozen rules meet, idempotency wins — and it has to.

    The README says a plan may only be submitted while planning, and that an
    identical resubmission returns the original receipt. Read the other way
    round the second rule could never fire: an accepted plan leaves the round in
    ``executing``, so the very replay the invariant exists for would be the one
    thing refused. A Bridge that never retries depends on this being the
    resolution — it is what makes "tell the leader it failed and let it ask
    again" a safe recovery rather than a way to plan twice.
    """

    lane = port()
    first = await lane.submit_plan(LEADER_TASK_ID_OF_FIXTURE, valid_plan())
    lane.worker_tasks_finished()

    assert await lane.submit_plan(LEADER_TASK_ID_OF_FIXTURE, valid_plan()) == first
    assert lane.phase == "review_due", "a replay reports; it does not rewind the round"


