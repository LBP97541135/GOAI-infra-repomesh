"""The Repository Leader lane, end to end against its own two adapters (PR 8).

Every document here comes from ``contracts/leader-actions/v1/fixtures``. Nothing
in this file hand-rolls a wire shape, because a test that spelled the contract
out a second time would go on passing after the freeze moved — which is the one
thing a consumer suite must not do. Where a shape is asserted it is asserted
with ``validate_document``, the same walker the wave-0 contract test uses, so a
schema construct neither side understands fails loudly in both suites at once.

Four things are checked and they need four different kinds of double:

* **The wire models** against the frozen fixtures, both directions.
* **The full lane** against ``InMemoryLeaderActionPort``, which really runs the
  phase machine. Planning to receipt to review to verdict, plus the refusals and
  the replays — all the claims the lane rests on, none of them faked.
* **The HTTP adapter** against the production FastAPI route, in process. Only
  ``GET`` exists on the server today (PR 7 lands the two writes), so that is
  what is covered: a 200 that parses, and the three refusals that must arrive as
  typed exceptions carrying the frozen code.
* **The coordination session** against a fake driver, where the load-bearing
  assertions are negative: no repository reaches the prompt or the process, a
  malformed answer is refused rather than repaired, and a model that writes its
  own provenance is turned away.

The leader notice fixture is generated by running RepoMesh's own leader-mode
assignment, not by copying its wording here. That is the only way the recogniser
stays honest: if the server rewords the notice, this test changes with it, and
if the server moves the *route*, this test fails — which is correct, because the
route is what the recogniser reads.
"""

