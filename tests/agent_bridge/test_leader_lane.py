async def test_closing_an_adapter_that_never_called_anything_is_safe() -> None:
    """The adapter holds a process-lifetime pool, so it owes a way to give it
    back — the same obligation the governed adapter carries, and it must not
    depend on a call having been made or on being closed only once."""

    resolutions = 0

    def credential() -> str:
        nonlocal resolutions
        resolutions += 1
        return "member-token"

    calls: list[str] = []

    async def answer(request: httpx.Request) -> httpx.Response:
        calls.append(str(request.url))
        return httpx.Response(200, json=load("assignment-package.planning.json"))

    lane = RepoMeshLeaderActionAdapter(
        endpoint="http://leader-actions.test",
        credential=credential,
        transport=httpx.MockTransport(answer),
    )

    await lane.close()
    await lane.close()

    assert calls == []
    assert resolutions == 0, "nothing resolved a secret it never needed"


