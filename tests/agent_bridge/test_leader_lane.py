async def test_the_leader_session_is_given_no_repository(tmp_path) -> None:
    """Adjudication D-8's second layer, asserted three ways.

    The prompt names no path on this machine; the process is started in the
    Bridge's own scratch directory rather than any checkout; and that directory
    holds nothing. The first is the one that matters most, because a fact
    package is the only thing about this lane that a future change could
    accidentally widen.
    """

    session, driver = await coordination(tmp_path, succeeded(plan_answer()))
    package = planning_package()

    await session.plan(package)

    request = driver.requests[0]
    prompt = request.prompt
    # Nothing from this machine is in the prompt: not the workspace, not the
    # session root, not the temp directory, not a drive letter.
    assert str(tmp_path) not in prompt
    assert str(request.workspace) not in prompt
    assert "\\" not in prompt and ":\\" not in prompt
    # And the working directory is not a repository: it is an empty scratch dir
    # the Bridge owns, with no checkout under it.
    assert request.workspace.is_dir()
    assert list(request.workspace.iterdir()) == []
    assert not (request.workspace / ".git").exists()
    # Nothing resumes: each decision is its own thread, so a verdict cannot lean
    # on remembering the plan instead of on the evidence.
    assert request.resume_session_id is None


